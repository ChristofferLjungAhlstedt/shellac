def logo_name(file_name: str) -> str | None:
    """Icon name for a regular file, or None to use the generic file icon."""
    found = FILENAME_ICONS.get(file_name) or FILENAME_ICONS.get(file_name.lower())
    if found is None:
        extension = os.path.splitext(file_name)[1].lstrip(".").lower()
        found = EXTENSION_ICONS.get(extension)
    return f"{ICON_PREFIX}{found}" if found else None
